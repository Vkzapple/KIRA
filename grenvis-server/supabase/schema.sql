-- =====================================================================
-- GRENVIS — skema Supabase
-- Jalankan di Supabase Dashboard -> SQL Editor (satu kali).
--
-- Catatan keamanan:
--   Backend memakai SERVICE ROLE KEY, jadi RLS tidak menghalangi server.
--   RLS diaktifkan tanpa policy tulis: anon key tidak bisa menulis.
--   Foto dibaca publik lewat bucket Storage "grenvis-snapshots".
-- =====================================================================

create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------- devices
create table if not exists public.devices (
  id         text primary key,
  name       text,
  kind       text,
  firmware   text,
  ip         text,
  last_seen  timestamptz not null default now()
);

-- --------------------------------------------------------------- telemetry
create table if not exists public.telemetry (
  id           bigint generated by default as identity primary key,
  device_id    text not null,
  soil_pct     int,
  soil_raw     int,
  distance_cm  int,
  distance_valid boolean not null default false,
  obstacle     boolean not null default false,
  sync_angle   int,
  aux_angle    int,
  motor        int,
  motor_target int,
  motor_left   int,
  motor_right  int,
  motor_left_target  int,
  motor_right_target int,
  cam_online   boolean not null default false,
  cam_armed    boolean not null default false,
  cam_busy     boolean not null default false,
  cam_target   text,
  rssi         int,
  uptime_s     bigint,
  created_at   timestamptz not null default now()
);

create index if not exists telemetry_created_at_idx
  on public.telemetry (created_at desc);
create index if not exists telemetry_device_time_idx
  on public.telemetry (device_id, created_at desc);

-- Migrasi untuk database yang dibuat sebelum kolom motor ada.
alter table public.telemetry add column if not exists motor int;
alter table public.telemetry add column if not exists motor_target int;
alter table public.telemetry add column if not exists motor_left int;
alter table public.telemetry add column if not exists motor_right int;
alter table public.telemetry add column if not exists motor_left_target int;
alter table public.telemetry add column if not exists motor_right_target int;

-- Migrasi kolom sensor ultrasonik HC-SR04 (deteksi objek di depan).
alter table public.telemetry add column if not exists distance_cm int;
alter table public.telemetry add column if not exists distance_valid boolean not null default false;
alter table public.telemetry add column if not exists obstacle boolean not null default false;

