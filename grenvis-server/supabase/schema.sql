-- --------------------------------------------------------------- snapshots
create table if not exists public.snapshots (
  id           uuid primary key,
  device_id    text not null,
  plant_name   text,
  image_path   text,
  image_url    text,
  class_name   text,
  confidence   double precision,
  captured_at  timestamptz not null default now(),
  created_at   timestamptz not null default now()
);

create index if not exists snapshots_captured_at_idx
  on public.snapshots (captured_at desc);
create index if not exists snapshots_device_time_idx
  on public.snapshots (device_id, captured_at desc);

-- -------------------------------------------------------------- detections
create table if not exists public.detections (
  id                uuid primary key,
  device_id         text,
  class_name        text not null,
  confidence        double precision,
  prediction_count  int,
  image_url         text,
  created_at        timestamptz not null default now()
);

create index if not exists detections_created_at_idx
  on public.detections (created_at desc);

-- --------------------------------------------------------------------- RLS
alter table public.devices    enable row level security;
alter table public.telemetry  enable row level security;
alter table public.snapshots  enable row level security;
alter table public.detections enable row level security;

-- ---------------------------------------------------------- storage bucket
insert into storage.buckets (id, name, public)
values ('grenvis-snapshots', 'grenvis-snapshots', true)
on conflict (id) do nothing;

drop policy if exists "grenvis snapshots public read" on storage.objects;
create policy "grenvis snapshots public read"
  on storage.objects for select
  using (bucket_id = 'grenvis-snapshots');
